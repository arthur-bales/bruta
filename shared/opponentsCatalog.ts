const OPPONENT_BY_ID: Record<string, OpponentDefinition> = Object.fromEntries(
  [...OPPONENTS_CATALOG, ...SEED_RIVAL_FIGHTERS].map((opp) => [opp.id, opp]),
);

export function getOpponentById(id: string): OpponentDefinition | undefined {
  return OPPONENT_BY_ID[id];
}

export function getAvailableOpponentsForLevel(level: number): OpponentDefinition[] {
  const maxVisibleLevel = Math.max(5, level + 6);
  return OPPONENTS_CATALOG.filter((opp, idx) => idx < 4 || opp.level <= maxVisibleLevel);
}
