import { instantiateEquipment } from './equipmentCatalog.js';
import type { EquippedGear, OpponentDefinition } from './types.js';

function makeGear(
  ids: Partial<Record<keyof EquippedGear, string>>,
  prefix: string,
  forgeLevel = 0,
): EquippedGear {
  const build = (slot: keyof EquippedGear) => {
    const tpl = ids[slot];
    if (!tpl) return null;
    const item = instantiateEquipment(tpl, `${prefix}_${slot}`);
    item.upgradeLevel = forgeLevel;
    return item;
  };
  return {
    weapon: build('weapon'),
    helmet: build('helmet'),
    armor: build('armor'),
    gloves: build('gloves'),
    boots: build('boots'),
    accessory: build('accessory'),
  };
}

